"""
Challenge 6 benchmark harness: time and cost for one pipeline configuration.

Run: `uv run python -m scripts.benchmark`            (3 real runs, costs money)
     `uv run python -m scripts.benchmark --dry-run`  (prints the plan, no API calls)

This script measures the pipeline; it is not part of it. Nothing here is
imported by `main.py`, `app.py`, or anything under `src/`.

Two things it deliberately does not do:

1. **It does not reimplement the pipeline.** It calls `main.run(...)` — the same
   function the CLI calls — and reads the `usage.json` that run wrote. What gets
   benchmarked is the real application architecture, so a later "after" arm
   measures the same seam rather than a lookalike.

2. **It does not put a clock anywhere in production.** `usage.py` records one
   normalized token record per API *response*; elapsed wall-clock is a property
   of a *run* and has no place on a response, which is why `build_report()`
   takes a bare sequence of records and knows nothing about when they arrived.
   The clock lives here, wrapped around the `main.run(...)` call, and nowhere
   else. `usage.json`'s schema is untouched.

Timing uses `time.perf_counter()` — a monotonic high-resolution clock that
cannot run backwards when the wall clock is adjusted mid-run.

The three-run/median methodology is deliberate: LLM latency is right-skewed by
occasional slow calls and by SDK-internal retries (the Anthropic SDK retries
408/409/429/5xx twice with backoff, invisibly), so a mean over three runs
overweights an outlier that the median ignores. Token and cost figures are
reported per run rather than averaged, because a difference there is a signal
about caching, not noise to be smoothed away.
"""

import argparse
import json
import statistics
import time
from datetime import datetime
from pathlib import Path
from typing import Any, Sequence

import main as main_module

ROOT = Path(__file__).resolve().parent.parent

# ---------------------------------------------------------------------------
# The fixed benchmark configuration
#
# Every Challenge 6 arm — sequential, parallel-naive, parallel-primed — must run
# this exact configuration, or the before/after comparison compares nothing. The
# inputs are the sample data the repo already ships: ten resumes regenerated by
# scripts/generate_sample_resumes.py from a checked-in dict, and the sample JD.
#
# deep_dive_top=3 is on purpose. It is the only setting that exercises *both*
# cached prefixes in one run: the scorer's (written once, read by every later
# candidate) and the deep-dive's own separate entry. A run without it would
# measure half the caching behaviour this challenge is about.
#
# self-critique and bias-audit stay off: each multiplies calls per resume and
# would inflate cost without telling us anything the two-call path doesn't.
# CSV stays off — it is deterministic, makes no API calls, and writing one more
# file is not what we are timing.
# ---------------------------------------------------------------------------

JD_PATH = ROOT / "sample_data" / "sample_jd.txt"
RESUMES_DIR = ROOT / "sample_data" / "resumes"

DEEP_DIVE_TOP = 3
SELF_CRITIQUE = False
BIAS_AUDIT = False
WRITE_CSV = False

DEFAULT_RUNS = 3

# Committed, because a baseline nobody can read later is not a baseline. The
# per-run pipeline outputs (results.json, report.md) go under output/, which is
# gitignored and regenerable; only the measurements live here.
ARTIFACT_DIR = ROOT / "benchmarks"
RUN_OUTPUT_ROOT = ROOT / "output" / "benchmark"

# Cached-prefix sizes observed on 2026-08-26 with the JD, prompts and tool
# schemas as they stand today.
#
# These are BENCHMARK OBSERVATIONS, not production invariants. Nothing in src/
# knows these numbers, no application behaviour depends on them, and they will
# change the moment the JD text or a prompt or a tool schema changes. They are
# used here for exactly one thing: putting a human-readable name next to a group
# of cache records so the report reads "scorer" instead of "1667". Prefix groups
# are always *derived* from the run's own usage data (see cache_prefix_summary);
# a size missing from this table is reported as an unrecognised prefix, never
# dropped and never treated as an error.
REFERENCE_PREFIXES: dict[int, str] = {
    1667: "scorer",
    1863: "deep-dive",
}

# Metrics that must not move between runs of the same configuration. Tokens and
# call counts are a property of the pipeline's shape; if one of these drifts,
# something changed that the benchmark needs to explain rather than average.
STABILITY_KEYS = (
    "call_count",
    "input_tokens",
    "cache_read_input_tokens",
    "cache_creation_input_tokens",
    "total_prompt_tokens",
)


# ---------------------------------------------------------------------------
# Pure helpers — every one of these is unit-testable from fake data
# ---------------------------------------------------------------------------


def count_pdfs(resumes_dir: Path) -> int:
    """How many resumes this configuration will process."""

    return len(sorted(p for p in resumes_dir.glob("*.pdf")))


def expected_call_count(
    n_resumes: int,
    deep_dive_top: int = DEEP_DIVE_TOP,
    self_critique: bool = SELF_CRITIQUE,
    bias_audit: bool = BIAS_AUDIT,
) -> int:
    """Rough LLM-call count, for the "this costs money" banner only.

    Not authoritative — `usage.json` is, because it counts responses that
    actually came back. This exists so nobody starts a paid run without seeing
    a number first.
    """

    per_resume = 2  # extract + score
    if self_critique:
        per_resume += 1
    if bias_audit:
        from src.bias_auditor import ALL_SWAPS

        per_resume += len(ALL_SWAPS)
    return n_resumes * per_resume + min(deep_dive_top, n_resumes)


def cache_prefix_summary(calls: Sequence[dict[str, Any]]) -> dict[int, dict[str, int]]:
    """Group a run's per-call records by cached-prefix size.

    Derived entirely from the run's own data: a call with
    `cache_creation_input_tokens > 0` wrote a prefix of that size, and one with
    `cache_read_input_tokens > 0` read a prefix of that size. Grouping by the
    token count separates the scorer's prefix from the deep-dive's without this
    function knowing either number, so it stays correct if the JD or a prompt
    changes and both sizes move.

    Returns {prefix_tokens: {"writes": n, "reads": n}}.
    """

    summary: dict[int, dict[str, int]] = {}
    for call in calls:
        written = call.get("cache_creation_input_tokens", 0) or 0
        read = call.get("cache_read_input_tokens", 0) or 0
        if written:
            summary.setdefault(written, {"writes": 0, "reads": 0})["writes"] += 1
        if read:
            summary.setdefault(read, {"writes": 0, "reads": 0})["reads"] += 1
    return dict(sorted(summary.items()))


def uncached_call_count(calls: Sequence[dict[str, Any]]) -> int:
    """Calls that touched no cache at all — extraction, in this pipeline."""

    return sum(
        1
        for c in calls
        if not (c.get("cache_creation_input_tokens") or c.get("cache_read_input_tokens"))
    )


def build_run_record(
    run_number: int, elapsed_seconds: float, usage: dict[str, Any]
) -> dict[str, Any]:
    """Flatten one run's elapsed time and its usage.json into a record.

    The whole `calls` array rides along so per-call cache behaviour can be
    re-examined later without re-running a paid benchmark.
    """

    totals = usage["totals"]
    calls = usage.get("calls", [])
    return {
        "run": run_number,
        "elapsed_seconds": round(elapsed_seconds, 2),
        "call_count": usage["call_count"],
        "models": usage["models"],
        "input_tokens": totals["input_tokens"],
        "cache_read_input_tokens": totals["cache_read_input_tokens"],
        "cache_creation_input_tokens": totals["cache_creation_input_tokens"],
        "total_prompt_tokens": totals["total_prompt_tokens"],
        "output_tokens": totals["output_tokens"],
        "estimated_cost_usd": usage["estimated_cost_usd"],
        "cache_prefixes": {
            str(size): counts for size, counts in cache_prefix_summary(calls).items()
        },
        "uncached_calls": uncached_call_count(calls),
        "calls": calls,
    }


def median_elapsed(records: Sequence[dict[str, Any]]) -> float:
    """Median wall-clock across runs. The headline number for an arm."""

    return statistics.median(r["elapsed_seconds"] for r in records)


def stability(
    records: Sequence[dict[str, Any]], keys: Sequence[str] = STABILITY_KEYS
) -> dict[str, bool]:
    """Which metrics held identical across every run. True means stable."""

    return {key: len({r[key] for r in records}) == 1 for key in keys}


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------

_ROWS = (
    ("Elapsed seconds", "elapsed_seconds"),
    ("API calls", "call_count"),
    ("Input tokens", "input_tokens"),
    ("Output tokens", "output_tokens"),
    ("Cache creation tokens", "cache_creation_input_tokens"),
    ("Cache read tokens", "cache_read_input_tokens"),
    ("Total prompt tokens", "total_prompt_tokens"),
    ("Estimated cost (USD)", "estimated_cost_usd"),
)


def format_table(records: Sequence[dict[str, Any]]) -> str:
    """One markdown table, one column per run. Paste-ready for the write-up."""

    header = "| Metric | " + " | ".join(f"Run {r['run']}" for r in records) + " |"
    rule = "| --- | " + " | ".join("---:" for _ in records) + " |"
    lines = [header, rule]
    for label, key in _ROWS:
        cells = []
        for r in records:
            value = r[key]
            if key == "estimated_cost_usd":
                cells.append("n/a" if value is None else f"${value:.6f}")
            elif key == "elapsed_seconds":
                cells.append(f"{value:.2f}")
            else:
                cells.append(f"{value:,}")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def format_cache_report(record: dict[str, Any]) -> str:
    """Per-prefix write/read counts for one run, with the reference comparison."""

    lines = [f"Run {record['run']} cache behaviour:"]
    lines.append(f"  uncached calls (no prefix): {record['uncached_calls']}")
    for size_str, counts in record["cache_prefixes"].items():
        size = int(size_str)
        name = REFERENCE_PREFIXES.get(size)
        label = (
            f"{name} (matches the 2026-08-26 reference)"
            if name
            else "unrecognised prefix - not in the reference table"
        )
        lines.append(
            f"  {size:,}-token prefix: {counts['writes']} write(s), "
            f"{counts['reads']} read(s)  <- {label}"
        )
    missing = sorted(
        size
        for size in REFERENCE_PREFIXES
        if str(size) not in record["cache_prefixes"]
    )
    for size in missing:
        lines.append(
            f"  {size:,}-token prefix ({REFERENCE_PREFIXES[size]}): NOT OBSERVED "
            f"this run - the reference no longer holds"
        )
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Running
# ---------------------------------------------------------------------------


def run_once(
    run_number: int, label: str, model: str, concurrency: int
) -> dict[str, Any]:
    """Time one full `main.run(...)` and read back the usage it wrote.

    The clock brackets the real entry point and nothing else, so elapsed time
    covers exactly the work the CLI does: parse, extract, score, deep-dive,
    report. Setup done here (choosing an output directory) is outside it.

    `concurrency` is the only thing that varies between arms. Every other
    argument is a module constant, so a "before" and an "after" run differ in
    exactly one input.
    """

    output_dir = RUN_OUTPUT_ROOT / label / f"run{run_number}"

    start = time.perf_counter()
    exit_code = main_module.run(
        str(JD_PATH),
        str(RESUMES_DIR),
        str(output_dir),
        model,
        SELF_CRITIQUE,
        BIAS_AUDIT,
        WRITE_CSV,
        DEEP_DIVE_TOP,
        concurrency,
    )
    elapsed = time.perf_counter() - start

    if exit_code != 0:
        raise RuntimeError(f"main.run() exited {exit_code} on run {run_number}")

    usage = json.loads((output_dir / "usage.json").read_text(encoding="utf-8"))
    return build_run_record(run_number, elapsed, usage)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Benchmark one Resume Matcher pipeline configuration.",
    )
    parser.add_argument(
        "--label",
        default="sequential",
        help=(
            "Name for this benchmark arm. Chooses the artifact filename "
            "(benchmarks/<label>.json). Default: sequential."
        ),
    )
    parser.add_argument(
        "--concurrency",
        type=int,
        default=1,
        help=(
            "Resumes processed at once. Defaults to 1 so a bare invocation "
            "reproduces the Stage 0 sequential arm. Pass 5 for parallel-naive."
        ),
    )
    parser.add_argument(
        "--runs",
        type=int,
        default=DEFAULT_RUNS,
        help=f"How many timed runs to execute (default: {DEFAULT_RUNS}).",
    )
    parser.add_argument(
        "--model",
        default=main_module.DEFAULT_MODEL,
        help=f"Claude model ID (default: {main_module.DEFAULT_MODEL}).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the plan and exit without making a single API call.",
    )
    args = parser.parse_args()

    n_resumes = count_pdfs(RESUMES_DIR)
    if n_resumes == 0:
        print(f"No resume PDFs in {RESUMES_DIR}.")
        print("Generate them: uv run python scripts/generate_sample_resumes.py")
        return 1

    per_run_calls = expected_call_count(n_resumes)
    print("Benchmark configuration")
    print("-" * 52)
    print(f"  label            {args.label}")
    print(f"  jd               {JD_PATH.relative_to(ROOT)}")
    print(f"  resumes          {RESUMES_DIR.relative_to(ROOT)} ({n_resumes} PDFs)")
    print(f"  model            {args.model}")
    print(f"  concurrency      {args.concurrency}")
    print(f"  deep_dive_top    {DEEP_DIVE_TOP}")
    print(f"  self_critique    {SELF_CRITIQUE}")
    print(f"  bias_audit       {BIAS_AUDIT}")
    print(f"  csv              {WRITE_CSV}")
    print(f"  runs             {args.runs}")
    print()
    print(
        f"  THIS IS A PAID BENCHMARK: about {per_run_calls} LLM calls per run, "
        f"{per_run_calls * args.runs} in total."
    )
    print()
    print(
        "  CACHE STATE: cached prefixes live 5 minutes and every read refreshes\n"
        "  that clock, so back-to-back runs are NOT independent - run 1 is the\n"
        "  only cold measurement unless nothing has touched these prefixes for\n"
        "  over 5 minutes. Compare cold arms against cold arms."
    )
    print()

    if args.dry_run:
        print("--dry-run: no API calls made. Re-run without it to measure.")
        return 0

    records: list[dict[str, Any]] = []
    for run_number in range(1, args.runs + 1):
        print(f"===== run {run_number}/{args.runs} =====")
        record = run_once(run_number, args.label, args.model, args.concurrency)
        records.append(record)
        print(f"\nrun {run_number}: {record['elapsed_seconds']:.2f}s\n")

    median = median_elapsed(records)
    stable = stability(records)

    print()
    print("=" * 52)
    print(f"Baseline summary - {args.label}")
    print("=" * 52)
    print()
    print(format_table(records))
    print()
    print(f"Median elapsed: {median:.2f}s")
    print()
    for record in records:
        print(format_cache_report(record))
    print()
    for key, is_stable in stable.items():
        print(f"  {'stable  ' if is_stable else 'VARIED  '}{key}")

    ARTIFACT_DIR.mkdir(exist_ok=True)
    artifact = ARTIFACT_DIR / f"{args.label}.json"
    artifact.write_text(
        json.dumps(
            {
                "label": args.label,
                "captured_at": datetime.now().astimezone().isoformat(timespec="seconds"),
                "configuration": {
                    "jd": str(JD_PATH.relative_to(ROOT)).replace("\\", "/"),
                    "resumes_dir": str(RESUMES_DIR.relative_to(ROOT)).replace("\\", "/"),
                    "n_resumes": n_resumes,
                    "model": args.model,
                    "deep_dive_top": DEEP_DIVE_TOP,
                    "self_critique": SELF_CRITIQUE,
                    "bias_audit": BIAS_AUDIT,
                    "csv": WRITE_CSV,
                    "concurrency": args.concurrency,
                },
                "runs": records,
                "summary": {
                    "median_elapsed_seconds": median,
                    "elapsed_seconds": [r["elapsed_seconds"] for r in records],
                    "stable_across_runs": stable,
                },
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print()
    print(f"Written to {artifact.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
